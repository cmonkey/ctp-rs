#pragma once

// CTP 版本门控 —— **数值比较**,不是 `#ifdef`。
//
// 为什么不用 #ifdef
// ------------------
// 收敛前这里是 `#ifdef CTP_6_7_11`,语义是二元的:「11 有 / 10 没有」。
// 那在只有两个版本时够用,但一旦加进 6.7.13 就全线崩坏 —— 那些 API 在
// 11 **和** 13 都有,16 处 `#ifdef` 会全部判错(13 走进"没有"的分支)。
//
// 逐处改成 `defined(A) || defined(B)` 只是把问题推后:**每加一个版本都要
// 再动一遍所有站点**,而且漏掉一处不会报错,只会悄悄走错分支。
//
// 数值比较一劳永逸:`#if CTP_VERSION_NUM >= 60711` 表达的是「6.7.11 起有」,
// 加 6.7.13、6.7.15 都不用碰这些站点。
//
// 为什么要 #error 守卫
// --------------------
// C 预处理器对未定义的标识符按 0 处理,所以少了这个定义,
// `#if CTP_VERSION_NUM >= 60711` 会静默变成 `0 >= 60711` = 假 ——
// 整个构建**悄无声息地退到低版本分支**,编译通过、测试通过、运行时才出事。
// 这正是本仓库反复吃过亏的那类静默失败,所以宁可让它编不过。
//
// 定义方在 `ctp-rs/build.rs`(按启用的 Cargo feature 推导)。

#if !defined(CTP_VERSION_NUM)
#error "CTP_VERSION_NUM 未定义。它由 ctp-rs/build.rs 按启用的 CTP 版本 feature 定义(如 ctp-6-7-11 → 60711)。若你是在 IDE/clangd 里看到这条,给 compile_commands 补上 -DCTP_VERSION_NUM=60711 即可;若是在真实构建里看到,说明 build.rs 的版本表没覆盖当前 feature。"
#endif

// 版本常量 —— 站点里直接写数字也行,这些只是让意图更明显。
#define CTP_V6_7_10 60710
#define CTP_V6_7_11 60711
#define CTP_V6_7_13 60713
